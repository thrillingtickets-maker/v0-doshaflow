// Regenerates lib/post-lastmod.ts: for each post, the date of its most recent
// real content change in git history, used as the sitemap <lastmod>.
// Run: node scripts/generate-post-lastmod.mjs
//
// A "real" change is a change to the post's visible text (title, excerpt, body)
// after its first appearance. Link text, markup, inline styles, SVG, JSON-LD,
// punctuation and escape/encoding differences are normalized away, and the
// commits below are skipped entirely because they were bulk formatting,
// encoding or linking passes rather than content edits.
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"

const NON_CONTENT_COMMITS = {
  "6640fa7": "automated stat-box insertion across all articles",
  "dc1d76b": "bulk removal of placeholder metric cards",
  "10e0a88": "highlight color styling",
  "b960af9": "duplicate footer element removal",
  "416ded5": "encoding repair",
  "7dea010": "encoding repair",
  "68a0130": "encoding repair",
  "c2e0b06": "ASCII-only conversion",
  "8339a0a": "internal linking pass",
  "6429711": "related-patterns link blocks",
  "7778786": "internal linking pass",
  "e62cbb8": "related-reading links",
  "5bbc701": "related-reading links",
  "16917ac": "broken internal link fixes",
  "38b7fe5": "dead internal link fix",
  "b538fd8": "contextual internal links + quiz CTA links",
  "24344ec": "link retargeting after stub cleanup",
  "c143011": "link relabeling",
  "a75a12c": "Vata/Kapha diet-plan contextual links",
  "0f97f6d": "Pitta diet-plan contextual links",
}

const git = (...args) => execFileSync("git", args, { maxBuffer: 1 << 30, encoding: "utf8" })

const str = (block, key) => {
  const m = block.match(new RegExp(`\\b${key}:\\s*(["'])((?:(?!\\1)[^\\\\]|\\\\[\\s\\S])*)\\1`))
  return m ? m[2] : ""
}
const tpl = (block) => block.match(/\bcontent:\s*`((?:[^`\\]|\\[\s\S])*)`/)?.[1] ?? ""

const normalize = (s) =>
  s
    .replace(/\\u\{?([0-9a-fA-F]{4,5})\}?/g, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/\\([\s\S])/g, "$1")
    .replace(/<(script|style|svg)\b[\s\S]*?<\/\1>/gi, " ")
    .replace(/<a\b[^>]*>[\s\S]*?<\/a>/gi, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/&[#\w]+;/g, " ")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .toLowerCase()
    .trim()

function parsePosts(text) {
  const out = new Map()
  const hits = [...text.matchAll(/\bslug:\s*(["'])([^"']+)\1/g)]
  hits.forEach((h, i) => {
    const slug = h[2]
    if (out.has(slug)) return
    const block = text.slice(h.index, i + 1 < hits.length ? hits[i + 1].index : text.length)
    const title = str(block, "title")
    const content = tpl(block)
    if (!title && !content) return
    out.set(slug, { text: normalize([title, str(block, "excerpt"), content].join(" \n ")), date: str(block, "date") })
  })
  return out
}

const toIso = (d) => {
  const t = Date.parse(`${d} UTC`)
  return Number.isNaN(t) ? undefined : new Date(t).toISOString().slice(0, 10)
}

const log = git("log", "--reverse", "--format=%H %cs", "--", "lib/posts.ts").trim().split("\n")
const prev = new Map()
const lastChange = new Map()
for (const line of log) {
  const [sha, day] = line.split(" ")
  let text
  try { text = git("show", `${sha}:lib/posts.ts`) } catch { continue }
  const cur = parsePosts(text)
  if (!(sha.slice(0, 7) in NON_CONTENT_COMMITS)) {
    for (const [slug, p] of cur) {
      const old = prev.get(slug)
      if (old && old.text !== p.text) lastChange.set(slug, day)
    }
  }
  for (const [slug, p] of cur) prev.set(slug, p)
}

const current = parsePosts(readFileSync("lib/posts.ts", "utf8"))
const entries = []
for (const [slug, p] of current) {
  const published = toIso(p.date)
  const changed = lastChange.get(slug)
  if (changed && (!published || changed > published)) entries.push([slug, changed])
}
entries.sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([s, d]) => `  ${JSON.stringify(s)}: "${d}",`).join("\n")
writeFileSync(
  "lib/post-lastmod.ts",
  `// Generated by scripts/generate-post-lastmod.mjs. Do not edit by hand.\n` +
    `// Date of each post's most recent real content change, when later than its\n` +
    `// publish date. Posts not listed use their publish date as lastmod.\n` +
    `export const postLastModified: Record<string, string> = {\n${body}\n}\n`,
)
console.log(`wrote ${entries.length} entries`)
